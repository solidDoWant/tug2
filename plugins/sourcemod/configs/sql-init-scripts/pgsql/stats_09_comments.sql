COMMENT ON COLUMN spawns.spawn_id IS 'Spawn key.';
COMMENT ON COLUMN spawns.round_id IS 'rounds.round_id.';
COMMENT ON COLUMN spawns.steam_id IS 'players.steam_id.';
COMMENT ON COLUMN spawns.spawned_at IS 'When they spawned.';
COMMENT ON TABLE spawn_items IS 'The loadout carried at each spawn: weapons, gear and upgrades by theater item name.';
COMMENT ON COLUMN spawn_items.spawn_id IS 'spawns.spawn_id.';
COMMENT ON COLUMN spawn_items.item_id IS 'items.item_id: join items for the theater item name.';

