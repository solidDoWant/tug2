COMMENT ON TABLE player_spans IS 'Stretches of a round a player spent on one team and class. Play time = security spans; medic time = medic class spans.';
COMMENT ON COLUMN player_spans.round_id IS 'rounds.round_id.';
COMMENT ON COLUMN player_spans.steam_id IS 'players.steam_id.';
COMMENT ON COLUMN player_spans.started_at IS 'Span start (round start, join, or team/class change).';
COMMENT ON COLUMN player_spans.ended_at IS 'Span end (round end, leaving, or team/class change).';
COMMENT ON COLUMN player_spans.team IS 'Team: security is the human players'' side.';
COMMENT ON COLUMN player_spans.squad IS 'Squad index; NULL if none.';
COMMENT ON COLUMN player_spans.squad_slot IS 'Slot within the squad; NULL if none.';
COMMENT ON COLUMN player_spans.class_template IS 'Class, e.g. template_medic_security; NULL before a class is picked.';
