COMMENT ON COLUMN hits.victim_team IS 'Victim''s team at the hit (humans and bots).';
COMMENT ON COLUMN hits.victim_bot_class_id IS 'Bot victim''s class (bot_classes.bot_class_id; v_hits has the name); NULL for humans.';
COMMENT ON COLUMN hits.victim_x IS 'Victim position (feet), world units.';
COMMENT ON COLUMN hits.victim_y IS 'Victim position, world units.';
COMMENT ON COLUMN hits.victim_z IS 'Victim position, world units (height).';
COMMENT ON COLUMN hits.attacker_steam_id IS 'Human who did the damage. NULL with attacker_bot_name NULL means the world (fall, fire, ...) or an unknown source.';
COMMENT ON COLUMN hits.attacker_bot_name IS 'Bot who did the damage.';
COMMENT ON COLUMN hits.attacker_team IS 'Attacker''s team at the hit; NULL for world damage.';
COMMENT ON COLUMN hits.attacker_bot_class_id IS 'Bot attacker''s class (bot_classes.bot_class_id; v_hits has the name); NULL for humans.';
COMMENT ON COLUMN hits.attacker_x IS 'Attacker position (feet) at the hit, world units. Distance = distance between the two positions.';
COMMENT ON COLUMN hits.attacker_y IS 'Attacker position, world units.';
