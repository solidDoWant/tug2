COMMENT ON COLUMN kills.round_id IS 'rounds.round_id.';
COMMENT ON COLUMN kills.killed_at IS 'When the death happened.';
COMMENT ON COLUMN kills.victim_steam_id IS 'Human victim. Exactly one of victim_steam_id and victim_bot_name is set.';
COMMENT ON COLUMN kills.victim_bot_name IS 'Bot victim''s name. Bot names repeat, so a name is not one bot.';
COMMENT ON COLUMN kills.victim_team IS 'Victim''s team at the death (humans and bots).';
COMMENT ON COLUMN kills.victim_bot_class_id IS 'Bot victim''s class (bot_classes.bot_class_id; v_kills has the name); NULL for humans.';
COMMENT ON COLUMN kills.victim_x IS 'Victim position, world units.';
COMMENT ON COLUMN kills.victim_y IS 'Victim position, world units.';
COMMENT ON COLUMN kills.victim_z IS 'Victim position, world units (height).';
COMMENT ON COLUMN kills.attacker_steam_id IS 'Human killer. NULL with attacker_bot_name NULL means a world death (fall, fire, ...).';
COMMENT ON COLUMN kills.attacker_bot_name IS 'Bot killer''s name.';
COMMENT ON COLUMN kills.attacker_team IS 'Killer''s team at the death; NULL for world deaths or an unknown killer.';
COMMENT ON COLUMN kills.attacker_bot_class_id IS 'Bot killer''s class (bot_classes.bot_class_id; v_kills has the name); NULL for humans.';
COMMENT ON COLUMN kills.attacker_x IS 'Killer position at the kill, world units. Kill distance = distance between the two positions.';
COMMENT ON COLUMN kills.attacker_y IS 'Killer position, world units.';
COMMENT ON COLUMN kills.attacker_z IS 'Killer position, world units (height).';
COMMENT ON COLUMN kills.assister_steam_id IS 'Human credited with the assist (the game picks the other enemy who did most damage).';
COMMENT ON COLUMN kills.assister_bot_name IS 'Bot credited with the assist.';
COMMENT ON COLUMN kills.weapon_name IS 'weapons.weapon_name; NULL for world deaths.';
COMMENT ON COLUMN kills.hitgroup IS 'Body part of the killing hit; NULL if not a bullet.';
COMMENT ON COLUMN kills.headshot IS 'The game flagged it a headshot kill.';
COMMENT ON COLUMN kills.domination IS 'The game flagged a domination.';
COMMENT ON COLUMN kills.revenge IS 'The game flagged a revenge kill.';
COMMENT ON COLUMN kills.savior IS 'The game flagged a savior kill (saved a teammate).';
COMMENT ON COLUMN kills.offensive IS 'Kill while attacking an objective.';
COMMENT ON COLUMN kills.defensive IS 'Kill while defending an objective.';
COMMENT ON COLUMN kills.damagebits IS 'Raw engine damage-type bit mask, undecoded.';
COMMENT ON COLUMN kills.customkill IS 'Raw engine kill subtype: 5 = melee bash; other values not understood.';
COMMENT ON COLUMN kills.attacker_stance IS 'Human killer''s stance; NULL for bots.';
COMMENT ON COLUMN kills.attacker_aim IS 'Human killer''s aim: hip, sights (iron sights or scope), bipod or focus; NULL for bots.';
COMMENT ON COLUMN kills.damage IS 'Health the killing blow took (what the victim had left). NULL for a death without damage (e.g. a team change).';
