COMMENT ON COLUMN hits.attacker_stance IS 'Human attacker''s stance; NULL for bots.';
COMMENT ON COLUMN hits.attacker_aim IS 'Human attacker''s aim: hip, sights (iron sights or scope), bipod or focus; NULL for bots.';
