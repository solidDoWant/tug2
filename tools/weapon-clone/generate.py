#!/usr/bin/env python3
"""Regenerates the upgrade restatements that make a new weapon accept its source weapon's upgrades.

A new weapon built on an existing one's model and animations (the XM8 on the Galil SAR's) can take
the same optics, suppressors, grips and so on - but TUG's upgrades name the weapons they fit, in
"allowed_weapons", in per-attachment "weapons" / "excluded_weapons" lists, in foregrip "scales" and
in per-weapon blocks such as "optics_fov_override" and weapon_mod_speed_reload's "weapon_mods". Each
of those has to name the new weapon too.

That means restating every such upgrade in theater_tug_nvg_default.theater: a definition declared in
a derived theater REPLACES the inherited one rather than merging into it (see the note atop the
"weapons" block there), so the copy has to be complete. Each copy is TUG's source text verbatim with
one thing added: wherever the source weapon is named, the new weapon is named beside it.

Attachments are the exception, because an attachment's model can be fitted to one weapon's geometry.
Those are listed per clone in ATTACHMENTS below, keyed by model path:

    None   the new weapon is NOT added - the part would float off its body (the Galil's rail mount on
           an XM8, which has an integrated rail)
    path   the attachment is copied under a new name, with this model, for the new weapon alone (the
           XM8's own bipod in place of the Galil's)

Anything else naming the source weapon is copied. Any mention the script does not recognise is an
error rather than a guess.

The output replaces everything between the BEGIN/END GENERATED markers in the base theater. Edit the
tables below and rerun; never hand-edit the generated block. Then rerun tools/survival-economy, which
reads these restatements to price survival's copies.

Usage:
    generate.py [--tug-dir DIR] [--theater-dir DIR]

--theater-dir is our theater sources, theaters/src/ by default. --tug-dir is TUG Scripts' theater
files, the vendored copy in theaters/vendor/ by default. This edits the SOURCE; run
`make theater-build` afterwards to regenerate the flattened theaters the servers load.
"""
import argparse
import os
import re
import sys
import tempfile

# The position-preserving KeyValues reader is shared with the survival price generator.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "survival-economy"))
from kv import Theater  # noqa: E402

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_THEATER_DIR = os.path.join(REPO, "theaters", "src")
DEFAULT_TUG_DIR = os.path.join(REPO, "theaters", "vendor", "tug-scripts-3.9")
BASE = "theater_tug_nvg_default.theater"
BEGIN = "// ===== BEGIN GENERATED by tools/weapon-clone/generate.py - do not edit by hand ====="
END = "// ===== END GENERATED (weapon-clone) ====="

# new weapon -> the weapon whose upgrades it takes
#
# Restating an upgrade is safe only because tools/theater-build keeps a restated upgrade in TUG's
# position. When the engine did the #base merge itself, every restated upgrade moved to the front
# of weapon_upgrades and got a new low id, and on 2026-10-15 - the first day this block shipped -
# all of them misrendered in first person on every weapon (a stray, unanimated carry handle on the
# M4A1 under any restated optic; the never-restated optic_scope_mk4 was fine). Their content is
# identical to TUG's apart from the clone's name (proven by reverse-engineering the merge), so the
# id move was the one difference. If that symptom returns with this block in place, empty CLONES
# again: the XM8 then keeps only what is defined for it by hand (magazine_cmag_xm8).
CLONES = {
    "weapon_xm8": "weapon_galil_sar",
}

# Per clone: attachment model -> None (leave the clone out) or the clone's own model.
ATTACHMENTS = {
    "weapon_xm8": {
        # The Galil's rail mount, shown under any optic. The XM8 has an integrated rail; the item
        # emptied this model to hide it.
        "models/weapons/upgrades/a_mount_galil.mdl": None,
        "models/weapons/upgrades/w_mount_galil.mdl": None,
        # The Galil's folded bipod, shown under a foregrip. Nothing to fold on the XM8; the item
        # emptied this model too.
        "models/weapons/upgrades/a_standard_galil.mdl": None,
        # The bipod itself: the item refitted it to the XM8's handguard.
        "models/weapons/upgrades/a_bipod_galil.mdl": "@@PATH(mdl,a_bipod_xm8.mdl)@@",
        "models/weapons/upgrades/w_bipod_galil.mdl": "@@PATH(mdl,w_bipod_xm8.mdl)@@",
    },
}

# Per clone: upgrades the clone does not get at all.
SKIP_UPGRADES = {
    # The Galil's 75-round drum. The XM8 has its own C-Mag (magazine_cmag_xm8, written by hand).
    "weapon_xm8": {"magazine_drum_75rd"},
}

ATTACHMENT_SECTIONS = ("viewmodel_attachments", "world_attachments")


def line_indent(src, pos):
    return src[src.rfind("\n", 0, pos) + 1:pos]


def insert_point(src, node):
    """Where a copy of node goes: end of its line when nothing else follows it there, else right
    after it. Keeps a trailing comment with the line it belongs to."""
    eol = src.find("\n", node.end)
    eol = len(src) if eol < 0 else eol
    rest = src[node.end:eol]
    if rest.strip() == "" or rest.strip().startswith("//"):
        return eol
    return node.end


def retarget_key(text, old, new):
    """text with its leading key token (possibly quoted) renamed."""
    m = re.match(r'("?)%s("?)' % re.escape(old), text, re.I)
    if not m:
        sys.exit("expected %r at start of %r" % (old, text[:40]))
    return m.group(1) + new + m.group(2) + text[m.end():]


def retarget_value(text, old, new):
    new_text, n = re.subn(r'("?)%s("?)(\s*)$' % re.escape(old), lambda m: m.group(1) + new + m.group(2) + m.group(3),
                          text, count=1, flags=re.I)
    if n != 1:
        sys.exit("expected value %r at end of %r" % (old, text))
    return new_text


def clone_attachment(src, att, new, model):
    """att's text under a new name, with a new model, for the new weapon alone."""
    text = att.text(src)
    m, ws = att.find("model"), att.find("weapons")
    ind = line_indent(src, ws.start)
    edits = [
        (m.start, m.end, m.text(src).replace(m.value, model)),
        (ws.start, ws.end, '"weapons"\n%s{\n%s\t"weapon"\t\t\t\t"%s"\n%s}' % (ind, ind, new, ind)),
    ]
    for a, b, rep in sorted(edits, reverse=True):
        text = text[:a - att.start] + rep + text[b - att.start:]
    suffix = new[len("weapon_"):] if new.startswith("weapon_") else new
    return retarget_key(text, att.key, "%s_%s" % (att.key, suffix))


def mentions(node, name):
    """Every node under node (inclusive) whose key or value is name."""
    out = []
    stack = [node]
    while stack:
        n = stack.pop()
        if n.key.lower() == name or (n.value or "").lower() == name:
            out.append(n)
        stack.extend(n.children or ())
    return out


def restate(src, upgrade, new, source, attachments):
    """The upgrade's text with new added wherever source is named, or None if nothing changed."""
    inserts = []             # (absolute position, text)
    handled = set()

    for section in ATTACHMENT_SECTIONS:
        sec = upgrade.find(section)
        for att in (sec.children or ()) if sec else ():
            ws = att.find("weapons")
            if ws is None or not any((c.value or "").lower() == source for c in ws.children or ()):
                continue
            model = att.find("model")
            path = model.value.lower().replace("\\", "/") if model is not None else None
            if path in attachments:
                for n in mentions(att, source):
                    handled.add(id(n))
                if attachments[path] is not None:
                    inserts.append((insert_point(src, att),
                                    "\n\n" + line_indent(src, att.start) +
                                    clone_attachment(src, att, new, attachments[path])))

    # Outermost first, so a block keyed by the source weapon is copied whole and nothing inside it is
    # copied a second time.
    for n in sorted(mentions(upgrade, source), key=lambda n: n.start):
        if id(n) in handled:
            continue
        text = n.text(src)
        if n.key.lower() == source:
            inner = [c for c in mentions(n, source) if c is not n]
            if inner:
                sys.exit("%s: %s names %s again inside itself; not a shape this script knows"
                         % (upgrade.key, n.key, source))
            copy = retarget_key(text, n.key, new)
        else:
            copy = retarget_value(text, n.value, new)
        handled.add(id(n))
        inserts.append((insert_point(src, n), "\n" + line_indent(src, n.start) + copy))

    if not inserts:
        return None
    text = upgrade.text(src)
    for pos, add in sorted(inserts, reverse=True):
        rel = pos - upgrade.start
        if not 0 <= rel <= len(text):
            sys.exit("insert outside %s" % upgrade.key)
        text = text[:rel] + add + text[rel:]
    return text


def load(theater_dir, tug_dir):
    """The theater chain with this script's own previous output removed from the base theater, so a
    rerun copies TUG's definitions and not its own."""
    src = open(os.path.join(theater_dir, BASE), encoding="utf-8").read()
    a, b = src.find(BEGIN), src.find(END)
    if a < 0 or b < 0:
        sys.exit("%s has no generated-block markers" % BASE)
    tmp = tempfile.mkdtemp()
    with open(os.path.join(tmp, BASE), "w", encoding="utf-8") as f:
        f.write(src[:a] + src[b + len(END):])
    return Theater(BASE, [tmp, theater_dir, tug_dir]), src


def build(theater):
    upgrades = theater.definitions("weapon_upgrades")
    out = []
    for new, source in CLONES.items():
        for name in sorted(upgrades):
            if name in SKIP_UPGRADES.get(new, ()):
                continue
            f, src, node = upgrades[name][0]
            # An upgrade that names the source only in a dead entry - optic_xps carries a Galil FOV
            # override but does not allow the Galil - does not fit the source either, so not the clone.
            allowed = node.find("allowed_weapons")
            if allowed is not None and not any((c.value or "").lower() == source
                                               for c in allowed.children or ()):
                continue
            text = restate(src, node, new, source, ATTACHMENTS.get(new, {}))
            if text is None:
                continue
            if f == BASE:
                sys.exit("%s is defined by hand in %s and names %s; add %s to it there"
                         % (node.key, BASE, source, new))
            out.append((node.key, f, new, source, text))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tug-dir", default=DEFAULT_TUG_DIR)
    ap.add_argument("--theater-dir", default=DEFAULT_THEATER_DIR)
    args = ap.parse_args()

    theater, src = load(args.theater_dir, args.tug_dir)
    items = build(theater)

    indent = line_indent(src, src.find(BEGIN))
    body = "\n\n".join("%s// from %s: %s added beside %s\n%s%s" % (indent, f, new, source, indent, text)
                       for _, f, new, source, text in items)
    a, b = src.find(BEGIN), src.find(END) + len(END)
    src = src[:a] + BEGIN + "\n\n" + body + "\n\n" + indent + END + src[b:]
    open(os.path.join(args.theater_dir, BASE), "w", encoding="utf-8").write(src)
    print("wrote %d upgrades to %s" % (len(items), BASE))


if __name__ == "__main__":
    main()
