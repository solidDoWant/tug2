#!/usr/bin/env python3
"""Flattens our theaters and the vendored TUG theaters they #base into self-contained theaters.

The engine never sees a #base again. Every theater this server loads is the output of this script:
one file per theater, holding the fully merged result, so how the engine combines a base with a
derived theater stops mattering - that combination happens here, once, where it can be read,
diffed and tested.

WHAT THE MERGE IS

Exactly what the engine did with these files at runtime, so flattening changes no content. Proven
by reverse-engineering the shipped server.so/client.so (KeyValues::LoadFromBuffer and
RecursiveMergeKeyValues - see theaters/README.md) and checked against the live server's item
tables:

  - "#base" "<file>" loads <file> in full, its own #base chain included, and after the including
    file is parsed each base is merged into it, in the order listed.
  - The merge walks the base's children. A child whose name matches the FIRST same-named child of
    the derived side (case-insensitive) is merged into it recursively; one with no match is
    appended, after the derived side's own children. A value is never overwritten, so the derived
    side always wins.
  - Consequences worth knowing: a declared definition is MERGED with TUG's, not substituted for it
    (TUG keys we leave out survive); a list of repeated keys ("weapon" "x", ...) that we declare
    replaces TUG's whole, because every inherited entry matches our first one; and a file reached
    twice through a diamond merges into itself, adding nothing.
  - Strings are taken raw - the theater loader does not process escape sequences, and TUG's model
    paths contain backslashes ("models\\weapons\\upgrades\\a_iron_enfield.mdl").

ONE DELIBERATE DEPARTURE: ORDER IN weapon_upgrades

Item ids are assigned in definition order, and the engine's merge puts the derived side's children
first - so restating one of TUG's upgrades moved it to the front and gave it a new, low id
(optic_eotech 87 -> 17). Every upgrade restated that way misrendered in first person on every
weapon (a stray, unanimated carry handle on the M4A1 under any restated optic) while an untouched
one on the same gun (optic_scope_mk4) was fine. The client-side mechanism is not pinned down, but
the content of a restated upgrade is otherwise identical to TUG's, so its position is the one thing
restating changed.

In the sections named in BASE_ORDER_SECTIONS, a merged definition therefore keeps the BASE's
position, and definitions only the derived side has go after all of the base's. Everywhere else
the merged order is the engine's. Do not widen this lightly: "ammo" in particular depends on its
order (its first entry is a deliberate sacrifice to the engine's index-0 ammo bug - see the
"ammo" section of theaters/src/theater_tug_nvg_default.theater).

ONE CLEAN-UP: ATTACHMENTS FOR WEAPONS THAT DO NOT EXIST

An attachment (a child of "viewmodel_attachments" / "world_attachments") restricts itself with a
"weapons" list, which the engine turns into a bitmask of weapon ids - and an EMPTY mask means the
attachment applies to EVERY weapon (proven in the client's per-weapon attachment filter). A name
that is not a registered weapon sets no bit. So an attachment whose list names only weapons that
are not in the theater - because we removed them, or because TUG named one it never defined - is
drawn on every weapon that takes the upgrade, bonemerged to bones that weapon does not have: it
floats in place and does not follow the viewmodel. Removing the Sterling and the L1A1 did exactly
that to base_optic_rail's ModKitSterling and ModKitL1A1 rail mounts, which every rail optic
inherits (a stray rail over the M4A1's own, static when the gun lowered); main, which still has
both weapons, was fine.

Such an attachment can never apply legitimately, so the build drops it and says so. Lists that name
at least one registered weapon are left alone (unknown names in them are inert), as are
"excluded_weapons" lists (unknown names there exclude nothing, which is harmless).

Usage:
    build.py build   [--src DIR] [--vendor DIR] [--out DIR]   write the flattened theaters
    build.py check   [--src DIR] [--vendor DIR] [--out DIR]   fail if --out is stale

Every *.theater in --src that does not start with "_" is an entry point and is written to --out
under the same name. #base targets resolve against --src first, then --vendor.
"""
import argparse
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_SRC = os.path.join(REPO, "theaters", "src")
DEFAULT_VENDOR = os.path.join(REPO, "theaters", "vendor", "tug-scripts-3.9")
DEFAULT_OUT = os.path.join(
    REPO, "server config", "test", "opt", "insurgency-server", "insurgency", "scripts", "theaters")

HEADER = """// GENERATED by tools/theater-build/build.py - do not edit.
//
// Flattened from theaters/src/%s and the vendored TUG theaters it #bases (theaters/vendor/).
// Edit the source and run `make theater-build`; `make theater-check` fails while this is stale.
"""


class KeyValuesError(Exception):
    pass


class KV:
    __slots__ = ("name", "value", "children")

    def __init__(self, name, value=None, children=None):
        self.name = name
        self.value = value          # str for a leaf
        self.children = children    # list for a block

    def copy(self):
        if self.children is None:
            return KV(self.name, self.value)
        return KV(self.name, children=[c.copy() for c in self.children])


# --------------------------------------------------------------------------------------------
# Parsing
# --------------------------------------------------------------------------------------------


def tokens(text, path):
    """(kind, text, line) with kind '{', '}' or 'str'. Quoted strings are raw: no escapes."""
    i, n, line = 0, len(text), 1
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            i += 1
        elif c.isspace():
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif c in "{}":
            yield c, c, line
            i += 1
        elif c == '"':
            j = text.find('"', i + 1)
            if j < 0:
                raise KeyValuesError("%s:%d: unterminated string" % (path, line))
            s = text[i + 1:j]
            yield "str", s, line
            line += s.count("\n")
            i = j + 1
        elif c == "[":
            raise KeyValuesError("%s:%d: [$...] conditionals are not modelled" % (path, line))
        else:
            j = i
            while j < n and not text[j].isspace() and text[j] not in '{}"':
                j += 1
            yield "str", text[i:j], line
            i = j


def parse_children(toks, path, closing):
    out = []
    while True:
        tok = next(toks, None)
        if tok is None:
            if closing:
                raise KeyValuesError("%s: unexpected end of file inside a block" % path)
            return out
        kind, text, line = tok
        if kind == "}":
            if not closing:
                raise KeyValuesError("%s:%d: unmatched '}'" % (path, line))
            return out
        if kind == "{":
            raise KeyValuesError("%s:%d: block with no name" % (path, line))
        nxt = next(toks, None)
        if nxt is None:
            raise KeyValuesError("%s:%d: key %r has no value" % (path, line, text))
        if nxt[0] == "{":
            out.append(KV(text, children=parse_children(toks, path, True)))
        elif nxt[0] == "str":
            out.append(KV(text, nxt[1]))
        else:
            raise KeyValuesError("%s:%d: key %r followed by '}'" % (path, line, text))


BASE_ORDER_SECTIONS = {"weapon_upgrades"}


def merge(this, base, depth=0):
    """RecursiveMergeKeyValues: base's children into this, first same-named match, derived wins.

    depth 0 is the top-level block ("theater"), so depth 1 is a section. In BASE_ORDER_SECTIONS the
    result is reordered so the base's order wins - see the module docstring."""
    if this.children is None:
        return
    base_order = depth == 1 and this.name.lower() in BASE_ORDER_SECTIONS
    placed, seen = [], set()
    for b in base.children or ():
        lname = b.name.lower()
        for d in this.children:
            if d.name.lower() == lname:
                merge(d, b, depth + 1)
                break
        else:
            d = b.copy()
            this.children.append(d)
        if base_order and id(d) not in seen:
            placed.append(d)
            seen.add(id(d))
    if base_order:
        this.children = placed + [d for d in this.children if id(d) not in seen]


class Loader:
    def __init__(self, dirs):
        self.dirs = dirs
        self.used = set()   # every file read, for the staleness check

    def resolve(self, name):
        for d in self.dirs:
            p = os.path.join(d, name)
            if os.path.isfile(p):
                return p
        raise KeyValuesError("#base %r not found in %s" % (name, ", ".join(self.dirs)))

    def load(self, name):
        """The file's top-level block with every #base merged in, as the engine builds it."""
        path = self.resolve(name)
        self.used.add(path)
        with open(path, encoding="latin-1", newline="") as f:  # raw bytes, as the engine sees them
            text = f.read()
        top = parse_children(tokens(text, path), path, False)
        bases = [kv.value for kv in top if kv.children is None and kv.name.lower() == "#base"]
        blocks = [kv for kv in top if kv.children is not None]
        stray = [kv.name for kv in top if kv.children is None and kv.name.lower() != "#base"]
        if stray:
            raise KeyValuesError("%s: unexpected top-level keys %s" % (path, stray))
        if len(blocks) != 1:
            raise KeyValuesError("%s: expected exactly one top-level block, found %d" % (path, len(blocks)))
        root = blocks[0]
        for b in bases:
            base = self.load(b)
            if base.name.lower() != root.name.lower():
                raise KeyValuesError("%s: #base %s has top-level block %r, not %r"
                                     % (path, b, base.name, root.name))
            merge(root, base)
        return root


# --------------------------------------------------------------------------------------------
# Output
# --------------------------------------------------------------------------------------------


def quote(s):
    if '"' in s:
        raise KeyValuesError("cannot write a string containing a double quote: %r" % s)
    return '"%s"' % s


def write(kv, depth, out):
    ind = "\t" * depth
    if kv.children is None:
        out.append("%s%s\t%s\n" % (ind, quote(kv.name), quote(kv.value)))
        return
    out.append("%s%s\n%s{\n" % (ind, quote(kv.name), ind))
    for c in kv.children:
        write(c, depth + 1, out)
    out.append("%s}\n" % ind)


ATTACHMENT_SECTIONS = ("viewmodel_attachments", "world_attachments")


def child(kv, name):
    name = name.lower()
    return next((c for c in kv.children or () if c.name.lower() == name), None)


def is_base(kv):
    b = child(kv, "IsBase")
    return b is not None and b.children is None and b.value not in ("0", "")


def drop_orphan_attachments(root):
    """Remove attachments whose "weapons" list names no registered weapon - see the docstring.
    Returns [(definition, section, attachment, [names])] for what was dropped."""
    weapons = child(root, "weapons")
    registered = {w.name.lower() for w in (weapons.children if weapons else ()) if not is_base(w)}
    dropped = []

    def walk(kv, owner):
        for c in kv.children or ():
            if c.children is None:
                continue
            if c.name.lower() in ATTACHMENT_SECTIONS:
                keep = []
                for att in c.children:
                    ws = child(att, "weapons") if att.children is not None else None
                    names = [w.value.lower() for w in (ws.children or ())
                             if w.children is None] if ws is not None else []
                    if names and not any(n in registered for n in names):
                        dropped.append((owner, c.name, att.name, names))
                    else:
                        keep.append(att)
                c.children = keep
            else:
                walk(c, owner)

    for section in root.children or ():
        for definition in section.children or ():
            if definition.children is not None:
                walk(definition, definition.name)
    return dropped


def render(name, root):
    out = [HEADER % name, "\n"]
    write(root, 0, out)
    return "".join(out)


def entry_points(src):
    return sorted(f for f in os.listdir(src) if f.endswith(".theater") and not f.startswith("_"))


def build_all(src, vendor, report=None):
    rendered = {}
    for name in entry_points(src):
        root = Loader([src, vendor]).load(name)
        dropped = drop_orphan_attachments(root)
        if report is not None:
            report[name] = dropped
        rendered[name] = render(name, root)
    return rendered


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("build", "check"))
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument("--vendor", default=DEFAULT_VENDOR)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    report = {}
    try:
        rendered = build_all(args.src, args.vendor, report)
    except KeyValuesError as e:
        sys.exit("theater-build: %s" % e)
    if not rendered:
        sys.exit("theater-build: no entry-point theaters in %s" % args.src)

    stale = []
    for name, text in rendered.items():
        path = os.path.join(args.out, name)
        try:
            with open(path, encoding="latin-1", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        stale.append(name)
        if args.command == "build":
            with open(path, "w", encoding="latin-1", newline="") as f:
                f.write(text)

    extra = sorted(f for f in os.listdir(args.out)
                   if f.endswith(".theater") and f not in rendered)
    if args.command == "check":
        if stale or extra:
            for name in stale:
                print("  stale:      %s" % name, file=sys.stderr)
            for name in extra:
                print("  not built:  %s (no source in %s)" % (name, args.src), file=sys.stderr)
            sys.exit("run `make theater-build` and commit the result")
        print("theaters are up to date with their sources")
        return
    for name in sorted(rendered):
        print("  %s %s" % ("wrote    " if name in stale else "unchanged", name))
    # The same attachments drop from every variant, so report them once, from the shortest name.
    first = min(report, key=len)
    if report[first]:
        print("dropped attachments that name no registered weapon (they would apply to every weapon):")
        for owner, section, att, names in report[first]:
            print("  %-28s %-22s %-20s %s" % (owner, section, att, ", ".join(names)))
    for name in extra:
        print("  warning: %s has no source in %s" % (name, args.src), file=sys.stderr)


if __name__ == "__main__":
    main()
